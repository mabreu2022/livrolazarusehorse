SET NAMES UTF8;

-- ============================================================================
-- 1. TABELA DE TENANTS (EMPRESAS / CLIENTES DA PLATAFORMA SAAS)
-- ============================================================================
CREATE TABLE tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_identificador VARCHAR(36) NOT NULL,
    razao_social VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(120),
    cnpj VARCHAR(18) NOT NULL,
    status VARCHAR(15) DEFAULT 'ATIVO' NOT NULL,
    plano VARCHAR(30) DEFAULT 'STANDARD' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT unq_tenants_uuid UNIQUE (uuid_identificador),
    CONSTRAINT unq_tenants_cnpj UNIQUE (cnpj),
    CONSTRAINT chk_tenants_status CHECK (status IN ('ATIVO', 'BLOQUEADO', 'CANCELADO'))
);

-- ============================================================================
-- 2. TABELA DE USUARIOS POR TENANT
-- ============================================================================
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    salt VARCHAR(64) NOT NULL,
    perfil VARCHAR(20) DEFAULT 'OPERADOR' NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_usuarios_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT unq_usuarios_tenant_email UNIQUE (tenant_id, email),
    CONSTRAINT chk_usuarios_perfil CHECK (perfil IN ('ADMIN', 'GERENTE', 'TECNICO', 'OPERADOR'))
);

CREATE INDEX idx_usuarios_tenant_email ON usuarios(tenant_id, email);

-- ============================================================================
-- 3. TABELA DE REFRESH TOKENS (SESSAO STATELESS JWT)
-- ============================================================================
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(128) NOT NULL,
    ip_origem VARCHAR(45),
    user_agent VARCHAR(255),
    expires_at TIMESTAMP NOT NULL,
    revogado BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_usuario FOREIGN KEY (usuario_id) 
        REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT unq_refresh_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_refresh_token_validacao ON refresh_tokens(usuario_id, revogado, expires_at);

-- ============================================================================
-- 4. TABELA DE CLIENTES (TOMADORES DE SERVICO)
-- ============================================================================
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    nome_razao VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(18) NOT NULL,
    email VARCHAR(120),
    telefone VARCHAR(20),
    logradouro VARCHAR(120),
    numero VARCHAR(20),
    complemento VARCHAR(60),
    bairro VARCHAR(60),
    cidade VARCHAR(80),
    uf VARCHAR(2),
    cep VARCHAR(10),
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_clientes_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT unq_clientes_tenant_doc UNIQUE (tenant_id, cpf_cnpj)
);

CREATE INDEX idx_clientes_tenant_nome ON clientes(tenant_id, nome_razao);

-- ============================================================================
-- 5. TABELA DE CATEGORIAS DE SERVICOS E PRODUTOS
-- ============================================================================
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    nome VARCHAR(80) NOT NULL,
    descricao VARCHAR(255),
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_categorias_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT unq_categorias_tenant_nome UNIQUE (tenant_id, nome)
);

-- ============================================================================
-- 6. TABELA DE PRODUTOS E SERVICOS
-- ============================================================================
CREATE TABLE produtos_servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    categoria_id BIGINT,
    tipo CHAR(1) NOT NULL, -- 'P' = Produto, 'S' = Servico
    codigo_interno VARCHAR(30),
    descricao VARCHAR(150) NOT NULL,
    valor_unitario NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    custo_unitario NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    estoque_atual NUMERIC(12, 3) DEFAULT 0.000 NOT NULL,
    ativo BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_prodserv_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_prodserv_categoria FOREIGN KEY (categoria_id) 
        REFERENCES categorias(id) ON DELETE SET NULL,
    CONSTRAINT chk_prodserv_tipo CHECK (tipo IN ('P', 'S')),
    CONSTRAINT chk_prodserv_valor CHECK (valor_unitario >= 0)
);

CREATE INDEX idx_prodserv_tenant_desc ON produtos_servicos(tenant_id, descricao);

-- ============================================================================
-- 7. TABELA DE ORDENS DE SERVICO (CABEALHO)
-- ============================================================================
CREATE TABLE ordens_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    numero_os VARCHAR(20) NOT NULL,
    cliente_id BIGINT NOT NULL,
    usuario_criacao_id BIGINT NOT NULL,
    usuario_tecnico_id BIGINT,
    status VARCHAR(20) DEFAULT 'ABERTA' NOT NULL,
    data_abertura TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_previsao TIMESTAMP,
    data_conclusao TIMESTAMP,
    valor_servicos NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    valor_produtos NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    valor_desconto NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    valor_total NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    defeito_relatado BLOB SUB_TYPE TEXT,
    laudo_tecnico BLOB SUB_TYPE TEXT,
    observacoes_internas BLOB SUB_TYPE TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_os_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_os_cliente FOREIGN KEY (cliente_id) 
        REFERENCES clientes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_os_usuario_criacao FOREIGN KEY (usuario_criacao_id) 
        REFERENCES usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT fk_os_usuario_tecnico FOREIGN KEY (usuario_tecnico_id) 
        REFERENCES usuarios(id) ON DELETE SET NULL,
    CONSTRAINT unq_os_tenant_numero UNIQUE (tenant_id, numero_os),
    CONSTRAINT chk_os_status CHECK (status IN ('ABERTA', 'EM_ANDAMENTO', 'PENDENTE', 'CONCLUIDA', 'CANCELADA', 'FATURADA'))
);

CREATE INDEX idx_os_tenant_status ON ordens_servico(tenant_id, status);
CREATE INDEX idx_os_tenant_cliente ON ordens_servico(tenant_id, cliente_id);
CREATE INDEX idx_os_tenant_abertura ON ordens_servico(tenant_id, data_abertura);

-- ============================================================================
-- 8. TABELA DE ITENS DA ORDEM DE SERVICO (PRODUTOS E SERVICOS LANCADOS)
-- ============================================================================
CREATE TABLE os_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    os_id BIGINT NOT NULL,
    produto_servico_id BIGINT NOT NULL,
    tipo CHAR(1) NOT NULL,
    quantidade NUMERIC(12, 3) NOT NULL,
    valor_unitario NUMERIC(15, 2) NOT NULL,
    desconto NUMERIC(15, 2) DEFAULT 0.00 NOT NULL,
    subtotal NUMERIC(15, 2) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_os_itens_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_os_itens_os FOREIGN KEY (os_id) 
        REFERENCES ordens_servico(id) ON DELETE CASCADE,
    CONSTRAINT fk_os_itens_item FOREIGN KEY (produto_servico_id) 
        REFERENCES produtos_servicos(id) ON DELETE RESTRICT,
    CONSTRAINT chk_os_itens_qtd CHECK (quantidade > 0)
);

CREATE INDEX idx_os_itens_os ON os_itens(os_id);

-- ============================================================================
-- 9. TABELA DE FATURAMENTO E CONTAS A RECEBER
-- ============================================================================
CREATE TABLE faturas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    os_id BIGINT,
    cliente_id BIGINT NOT NULL,
    numero_fatura VARCHAR(30) NOT NULL,
    valor NUMERIC(15, 2) NOT NULL,
    data_emissao DATE DEFAULT CURRENT_DATE NOT NULL,
    data_vencimento DATE NOT NULL,
    data_pagamento TIMESTAMP,
    status VARCHAR(20) DEFAULT 'PENDENTE' NOT NULL,
    forma_pagamento VARCHAR(30),
    transacao_gateway_id VARCHAR(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_faturas_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE,
    CONSTRAINT fk_faturas_os FOREIGN KEY (os_id) 
        REFERENCES ordens_servico(id) ON DELETE SET NULL,
    CONSTRAINT fk_faturas_cliente FOREIGN KEY (cliente_id) 
        REFERENCES clientes(id) ON DELETE RESTRICT,
    CONSTRAINT unq_faturas_tenant_num UNIQUE (tenant_id, numero_fatura),
    CONSTRAINT chk_faturas_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO', 'VENCIDO'))
);

CREATE INDEX idx_faturas_tenant_status ON faturas(tenant_id, status);
CREATE INDEX idx_faturas_tenant_venc ON faturas(tenant_id, data_vencimento);

-- ============================================================================
-- 10. TABELA DE LOGS DE AUDITORIA (COMPLIANCE E SEGURANCA)
-- ============================================================================
CREATE TABLE auditoria_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    usuario_id BIGINT,
    acao VARCHAR(30) NOT NULL,       -- 'INSERT', 'UPDATE', 'DELETE', 'LOGIN', 'ERROR'
    recurso VARCHAR(60) NOT NULL,    -- 'ORDEM_SERVICO', 'FATURA', 'AUTENTICACAO'
    recurso_id VARCHAR(50),
    ip_origem VARCHAR(45),
    user_agent VARCHAR(255),
    dados_payload BLOB SUB_TYPE TEXT,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_tenant FOREIGN KEY (tenant_id) 
        REFERENCES tenants(id) ON DELETE CASCADE
);

CREATE INDEX idx_audit_tenant_data ON auditoria_logs(tenant_id, data_hora);

-- ============================================================================
-- 11. TRIGGERS DE ATUALIZACAO AUTOMATICA DO TIMESTAMP UPDATED_AT
-- ============================================================================
SET TERM ^ ;

CREATE OR ALTER TRIGGER trg_tenants_updated_at FOR tenants
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER trg_usuarios_updated_at FOR usuarios
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER trg_clientes_updated_at FOR clientes
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER trg_prodserv_updated_at FOR produtos_servicos
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER trg_os_updated_at FOR ordens_servico
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

CREATE OR ALTER TRIGGER trg_faturas_updated_at FOR faturas
ACTIVE BEFORE UPDATE POSITION 0
AS
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
END^

SET TERM ; ^

